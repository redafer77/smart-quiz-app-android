def apply_to_line(line):
    """يعيد السطر بعد استبدال مشتّتاته، أو None إن لم يكن مشمولاً."""
    parts = line.split("|")
    if len(parts) != 7:
        return None
    level, question, options, answer = parts[0], parts[1], parts[2:6], int(parts[6])
    correct = options[answer - 1]

    if question in REWRITES:
        question, correct, distractors = REWRITES[question]
    elif question in PATCHES:
        distractors = PATCHES[question]
    else:
        return None

    # الإجابة تبقى في موضعها الأصلي حتى لا يختل توازن المواضع المضبوط سلفاً
    new_options = list(distractors)
    new_options.insert(answer - 1, correct)
    return "|".join([level, question] + new_options + [str(answer)])


def main():
    seen = set()
    changed = 0
    for name in sorted(os.listdir(SOURCE_DIR)):
        if not name.endswith(".txt"):
            continue
        path = os.path.join(SOURCE_DIR, name)
        with open(path, "r", encoding="utf-8") as handle:
            lines = handle.read().split("\n")
        out = []
        for line in lines:
            stripped = line.strip()
            new = apply_to_line(stripped) if stripped and not stripped.startswith("#") else None
            if new is None:
                out.append(line)
            else:
                seen.add(stripped.split("|")[1])
                out.append(new)
                changed += 1
        with open(path, "w", encoding="utf-8") as handle:
            handle.write("\n".join(out))

    missed = (set(PATCHES) | set(REWRITES)) - seen
    if missed:
        print("لم يُعثر على %d سؤال:" % len(missed))
        for q in sorted(missed):
            print("  -", q)
        sys.exit(1)
    print("عُدّل %d سؤالاً في ملفات المصدر." % changed)


if __name__ == "__main__":
    main()
